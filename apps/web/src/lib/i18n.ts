export function label(value: string | null | undefined, lang: Locale = "vi") {
  if (!value) return lang === "vi" ? "Chưa rõ" : "Unknown";
  return labels[value]?.[lang === "vi" ? 0 : 1] || value;
}
export function money(amount: number, currency = "VND") {
  return new Intl.NumberFormat("vi-VN", {
    style: "currency",
    currency,
    maximumFractionDigits: currency === "VND" ? 0 : 2,
  }).format(currency === "VND" ? amount : amount / 100);
}
export function date(value: string | null, lang: Locale = "vi") {
  return value
    ? new Intl.DateTimeFormat(lang === "vi" ? "vi-VN" : "en-GB", {
        day: "numeric",
        month: "short",
        timeZone: "Asia/Ho_Chi_Minh",
      }).format(new Date(value))
    : "—";
}
